import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';

await mkdir('artifacts', { recursive: true });
const browser = await chromium.launch({ channel: process.platform === 'win32' ? 'msedge' : 'chromium', headless: true });
const page = await browser.newPage({ viewport: { width: 1360, height: 900 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.goto('http://127.0.0.1:5173/?demo=1');
await page.getByRole('button', { name: 'New session', exact: false }).first().waitFor();
await page.screenshot({ path: 'artifacts/relay-preview.png' });
await page.getByRole('button', { name: 'Notifications', exact: false }).first().click();
await page.getByRole('heading', { name: 'Notifications', exact: true }).waitFor();
await page.screenshot({ path: 'artifacts/relay-inbox.png' });
await page.getByRole('button', { name: 'Background rules', exact: false }).click();
await page.getByRole('heading', { name: 'Background rules', exact: true }).waitFor();
await page.getByRole('button', { name: 'New rule', exact: false }).click();
await page.getByRole('dialog').waitFor();
await page.screenshot({ path: 'artifacts/relay-rule-editor.png' });
await page.keyboard.press('Escape');
await page.getByRole('button', { name: 'Create group', exact: true }).click();
await page.getByRole('textbox', { name: 'Group name', exact: true }).fill('QA group');
await page.getByRole('dialog').getByRole('button', { name: 'Save', exact: false }).click();
await page.getByRole('button', { name: 'QA group', exact: false }).first().waitFor();
await page.reload();
await page.getByRole('button', { name: 'Workspace', exact: false }).first().waitFor();
await page.setViewportSize({ width: 900, height: 640 });
await page.screenshot({ path: 'artifacts/relay-small-preview.png' });
if (errors.length) throw new Error(errors.join('\n'));
console.log('Preview checks passed: terminal, inbox, rules editor, group action, isolated demo reload, small layout; no page errors.');
await browser.close();
